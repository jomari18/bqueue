/**
 * Writes docs/fil-review.md: every message key with its English and Filipino text side by side, for a native
 * speaker to review before go-live (Task 35). Run it again whenever the messages change:
 *
 *   node tools/fil-review.mjs
 */
import { readFile, writeFile } from "node:fs/promises";

const at = (path) => new URL(`../${path}`, import.meta.url);
const en = JSON.parse(await readFile(at("apps/web/messages/en.json"), "utf8"));
const fil = JSON.parse(await readFile(at("apps/web/messages/fil.json"), "utf8"));

function flatten(obj, prefix = "") {
  return Object.entries(obj).flatMap(([k, v]) => (v && typeof v === "object" ? flatten(v, `${prefix}${k}.`) : [[`${prefix}${k}`, String(v)]]));
}
const cell = (text) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

const filByKey = new Map(flatten(fil));
const rows = flatten(en).map(([key, text]) => {
  const tl = filByKey.get(key);
  return `| \`${key}\` | ${cell(text)} | ${tl === undefined ? "**MISSING**" : tl === text ? `${cell(tl)} _(same as English)_` : cell(tl)} |`;
});
const namespaces = new Set(flatten(en).map(([key]) => key.split(".")[0]));

const md = `# Filipino review sheet

Generated by \`tools/fil-review.mjs\` from \`apps/web/messages\`. ${rows.length} strings in ${namespaces.size} groups.

For the reviewer: read the Filipino column as a resident at the barangay hall would. Mark anything stiff, too deep, or
wrong, and suggest the everyday Taglish a kagawad or staff member would actually say. Placeholders in braces, such as
\`{counter}\`, are filled in by the app and must stay as they are.

| Key | English | Filipino |
| --- | --- | --- |
${rows.join("\n")}
`;
await writeFile(at("docs/fil-review.md"), md);
console.log(`Wrote docs/fil-review.md (${rows.length} strings)`);
